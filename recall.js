function recallNormalize(s){ return normalize(s).replace(/블렌디드/g,'블랜디드'); }
function splitRecallInput(text, core){
    text=text.replace(/^\s*\d+\s*[.)、:]\s*/gm,'');
    return text.split(core ? /\n+|(?<=[.!?。])\s*/ : /[\n,，;；]+/)
        .map(s=>s.replace(/^\s*(?:\d+\s*[.)、:]|[-•●⋅])\s*/,'').trim()).filter(Boolean);
}
function recallSimilarity(a,b){
    a=recallNormalize(a); b=recallNormalize(b);
    let row=Array.from({length:b.length+1},(_,i)=>i);
    for(let i=1;i<=a.length;i++){
        const next=[i];
        for(let j=1;j<=b.length;j++) next[j]=Math.min(next[j-1]+1,row[j]+1,row[j-1]+(a[i-1]===b[j-1]?0:1));
        row=next;
    }
    return 1-row[b.length]/Math.max(a.length,b.length,1);
}
function gradeRecall(items, entries){
    const unused=new Set(entries.map((_,i)=>i));
    const rows=items.map(correct=>{
        const index=[...unused].find(i=>recallNormalize(entries[i])===recallNormalize(correct));
        if(index!==undefined){ unused.delete(index); return {correct,user:entries[index],ok:true}; }
        return {correct,user:'',ok:false};
    });
    for(const row of rows.filter(r=>!r.ok)){
        let best=-1,score=.35;
        for(const i of unused){
            if(items.some(s=>recallNormalize(s)===recallNormalize(entries[i]))) continue;
            const similarity=recallSimilarity(entries[i],row.correct);
            if(similarity>score){best=i;score=similarity;}
        }
        if(best>=0){row.user=entries[best];unused.delete(best);}
    }
    return {rows,extras:[...unused].map(i=>({text:entries[i],duplicate:items.some(s=>recallNormalize(s)===recallNormalize(entries[i]))}))};
}
function checkRecallAnswer(){
    if(recallChecked) return;
    const {rows,extras}=gradeRecall(current.items,splitRecallInput(answer.value,appMode==='core'));
    const count=rows.filter(r=>r.ok).length;
    const success=count===rows.length && extras.every(e=>e.duplicate);
    if(success) recallWrong.delete(current.id); else recallWrong.add(current.id);
    if(studyMode==='blank') updateLevel(success);
    result.innerHTML=`<b class="${success?'recallCorrect':'recallWrong'}">${success?'⭕ 정답':'❌ 다시 확인'} · ${count} / ${rows.length}개 회수</b>`+
        rows.map(r=>`<div class="recallFeedback">${r.ok?`<span class="recallCorrect">✓ ${escapeHtml(r.correct)}</span>`:r.user?`<span class="recallWrong">오답 입력: ${escapeHtml(r.user)}</span><br>정답: ${makeDifferenceMarkup(r.user,r.correct)}`:`<span class="recallWrong">누락: ${escapeHtml(r.correct)}</span>`}</div>`).join('')+
        extras.map(e=>`<div class="recallWrong">${e.duplicate?'중복 (한 번만 인정)':'목록 밖 입력'}: ${escapeHtml(e.text)}</div>`).join('');
    question.textContent=current.items.map((s,i)=>`${i+1}. ${s}`).join('\n'); question.style.display='block';
    if(studyMode==='blank') result.innerHTML+=`<p>Lv.${getLevel(current.id).level}</p>`;
    recallChecked=true;
}
function nextRecallQuestion(){
    if(!recallChecked) recallWrong.add(current.id);
    if(currentIndex<questions.length-1){currentIndex++;showRecallQuestion();return;}
    if(recallWrong.size){
        questions=recallOriginal.filter(q=>recallWrong.has(q.id));
        alert(`미완료·오답 ${questions.length}개 묶음을 다시 인출합니다.`);
    }else{ alert('모두 인출했습니다. 전체를 다시 연습합니다.'); questions=[...recallOriginal]; }
    currentIndex=0; showRecallQuestion();
}
